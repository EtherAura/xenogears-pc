#!/usr/bin/env python3
"""Build/embed the OFL pixel fallback used for Japanese OST titles and the
interface's Japanese (port/src/ui/lang/*.po).

Regenerate once using fontTools (not needed for normal builds):
  python tools/jukebox_font.py subset SOURCE.ttc OUTPUT.otf
  python tools/jukebox_font.py raster SOURCE glyphs.bin  # requires Pillow
SOURCE is Noto Sans CJK JP Regular 2.001 (the .ttc's first face, or the subset
.otf when it holds every character): both give the same bits.
Normal CMake builds use only Python's standard library:
  python tools/jukebox_font.py embed glyphs.bin OUTPUT.h
The native disc font supplies available glyphs; this covers missing ones.
"""
import pathlib
import sys
import struct


def characters(root):
    """The OST titles' characters and every translated interface string's."""
    text = (root / 'port/src/extras/jukebox_titles.cpp').read_text(encoding='utf-8')
    sys.path.insert(0, str(root / 'tools'))
    import l10n
    for po in sorted((root / 'port/src/ui/lang').glob('*.po')):
        text += ''.join(e.msgstr for e in l10n.read_po(po) if l10n.usable(e) is None)
    return sorted({c for c in text if ord(c) > 127})


def main():
    mode, source, output = sys.argv[1:]
    source, output = pathlib.Path(source), pathlib.Path(output)
    if mode == 'embed':
        data = source.read_bytes()
        if len(data) % 26: raise ValueError('Expected 26-byte Unicode/11-row glyph records')
        rows = []
        for at in range(0, len(data), 26):
            code, *bits = struct.unpack_from('<I11H', data, at)
            rows.append('    {0x%04x, {%s}}' % (code, ', '.join('0x%04x' % b for b in bits)))
        text = '// Generated by tools/jukebox_font.py; font licence in third_party/jukebox-font/LICENSE.txt.\n'
        text += 'static const struct { uint32_t unicode; uint16_t rows[11]; } japaneseFallback[] = {\n'
        text += ',\n'.join(rows) + '\n};\n'
        output.parent.mkdir(parents=True, exist_ok=True)
        if not output.exists() or output.read_text() != text:
            output.write_text(text)
    elif mode == 'raster':
        from PIL import Image, ImageDraw, ImageFont
        root = pathlib.Path(__file__).resolve().parent.parent
        chars = characters(root)
        font = ImageFont.truetype(str(source), 11)
        data = bytearray()
        for c in chars:
            image = Image.new('L', (12, 11))
            ImageDraw.Draw(image).text((0, -font.getbbox(c)[1]), c, font=font, fill=255)
            rows = [sum(1 << bit for x, bit in enumerate([7, 6, 5, 4, 3, 2, 1, 0, 15, 14, 13, 12])
                        if image.getpixel((x, y)) >= 96) for y in range(11)]
            data.extend(struct.pack('<I11H', ord(c), *rows))
        output.write_bytes(data)
    elif mode == 'subset':
        from fontTools import subset
        from fontTools.ttLib import TTFont
        root = pathlib.Path(__file__).resolve().parent.parent
        chars = [ord(c) for c in characters(root)]
        font = TTFont(source, fontNumber=0, recalcTimestamp=False)
        for code in chars:
            if code not in font.getBestCmap(): raise ValueError(f'No glyph for U+{code:04X}')
        options = subset.Options()
        options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=chars)
        subsetter.subset(font)
        for name in font['name'].names:
            label = {1: 'Jukebox Japanese', 3: 'Jukebox Japanese Regular',
                     4: 'Jukebox Japanese Regular', 6: 'JukeboxJapanese-Regular'}.get(name.nameID)
            if label: name.string = label.encode(name.getEncoding())
        if 'CFF ' in font:
            font['CFF '].cff.fontNames = ['JukeboxJapanese-Regular']
            top = font['CFF '].cff.topDictIndex[0]
            top.FamilyName, top.FullName = 'Jukebox Japanese', 'Jukebox Japanese Regular'
        output.parent.mkdir(parents=True, exist_ok=True)
        font.save(output)
        print(f'{len(chars)} title characters, {output.stat().st_size} font bytes')
    else:
        raise ValueError('Expected subset, raster or embed')


if __name__ == '__main__':
    main()
