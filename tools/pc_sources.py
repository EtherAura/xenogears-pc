#!/usr/bin/env python3
"""Write the PC port's CMake source lists (build/pc/sources.cmake).

    python tools/pc_sources.py

The port (port/CMakeLists.txt) compiles the same game C as the matching build.
This lists it per version and module, from the splat configs' C subsegments
(a few files exist for one version only), so the two builds share one source
of truth:

    set(XG_MODULES_US main field ...)
    set(XG_SOURCES_US_main <abs paths>)
    ...

The PsyQ SDK copies (src/main/psyq/, src/video_player/psyq/) are left out: the
port's platform layer replaces them. tools/configure.py runs this too.
"""

from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
EXCLUDE = ("src/main/psyq/", "src/video_player/psyq/")
VERSIONS = ("us", "jp")


# Subsegment kinds that name a C file: its code (c) or, for a data-only file
# such as sound_data.c, just its sections.
C_KINDS = {"c", ".data", ".rodata", ".bss", ".sdata", ".sbss"}


def c_names(config: Path) -> list[str]:
    """The C files a splat module config builds (some exist for one version only)."""
    names = []
    for seg in yaml.safe_load(config.read_text()).get("segments", []):
        if not isinstance(seg, dict):
            continue
        for sub in seg.get("subsegments", []):
            if isinstance(sub, list) and len(sub) > 2 and sub[1] in C_KINDS:
                name = str(sub[2])
            elif isinstance(sub, dict) and sub.get("type") in C_KINDS and "name" in sub:
                name = str(sub["name"])
            else:
                continue
            if name not in names:
                names.append(name)
    return names


def modules(version: str) -> dict[str, list[Path]]:
    manifest = yaml.safe_load((ROOT / "config" / version / "disc.yaml").read_text())
    mods: dict[str, list[Path]] = {}
    for entry in manifest["files"]:
        config = ROOT / "config" / version / f"{entry['name']}.yaml"
        if not config.is_file():
            continue
        files = []
        for name in c_names(config):
            path = ROOT / "src" / entry["name"] / f"{name}.c"
            if path.is_file() and not path.relative_to(ROOT).as_posix().startswith(EXCLUDE):
                files.append(path)
        if files:
            mods[entry["name"]] = files
    # main first: the other modules link against it.
    return dict(sorted(mods.items(), key=lambda kv: (kv[0] != "main", kv[0])))


def write(out: Path = ROOT / "build/pc/sources.cmake") -> Path:
    lines = ["# Generated by tools/pc_sources.py; do not edit."]
    for version in VERSIONS:
        mods = modules(version)
        lines.append(f"set(XG_MODULES_{version.upper()} {' '.join(mods)})")
        for name, files in mods.items():
            lines.append(f"set(XG_SOURCES_{version.upper()}_{name}")
            # Relative to XG_GAME_ROOT (port/CMakeLists.txt): the matched C in src/, or
            # the Enhanced engine's fork of it in engine/src (tools/fork_engine.py).
            lines += [f"    ${{XG_GAME_ROOT}}/{f.relative_to(ROOT).as_posix()}" for f in files]
            lines.append(")")
    out.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out


if __name__ == "__main__":
    print(write())
